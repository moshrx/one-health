import { test, expect } from '@playwright/test';
test('registration through consultation, references, comparison, approval and follow-up',async({page})=>{
 await page.goto('/');
 await page.screenshot({path:'preview-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'New patient',exact:true}).click();
 await page.getByLabel('Full name').fill('Fictional Taylor');
 await page.getByLabel('Age',{exact:true}).fill('35');
 await page.getByLabel('Presenting complaint').fill('Demonstration history');
 await page.getByLabel('Adults',{exact:true}).check();
 await page.getByRole('button',{name:'Create patient'}).click();
 await page.getByLabel('Chief complaint & duration',{exact:true}).fill('Fictional complaint for two days');
 await page.getByLabel('Red flags & referral plan',{exact:true}).fill('Reviewed in this fictional scenario');
 await page.getByRole('button',{name:'Review & sign case'}).click();
 await expect(page.locator('.timeline')).toContainText('Signed');
 await page.reload();
 await page.locator('nav').getByRole('button',{name:'Patients',exact:true}).click();
 await page.getByLabel('Search patients').fill('Fictional Taylor');
 await page.getByRole('button',{name:'Fictional Taylor',exact:true}).click();
 await expect(page.getByLabel('Chief complaint & duration',{exact:true})).toHaveValue('Fictional complaint for two days');
 await page.locator('nav').getByRole('button',{name:'Materia Medica Books',exact:true}).click();
 await page.getByLabel('Search reference library').fill('Boericke');
 await expect(page.locator('.book')).toHaveCount(1);
 await page.getByRole('button',{name:'View collection'}).click();
 await expect(page.locator('.detail')).toContainText('awaiting a licensed');
 await page.locator('nav').getByRole('button',{name:'Repertorization',exact:true}).click();
 await page.getByLabel('Weight Head · pain (illustrative)').selectOption('2');
 await expect(page.locator('.ranking').first()).toContainText('Bryonia alba');
 await page.getByRole('button',{name:'Save comparison'}).click();
 await expect(page.locator('.timeline')).toContainText('Repertorization');
 await page.locator('nav').getByRole('button',{name:'Prescription',exact:true}).click();
 await page.getByRole('button',{name:'Approve & sign prescription'}).click();
 await expect(page.getByRole('status')).toContainText('Complete every prescription field');
 for(const input of await page.locator('.form-grid textarea').all()) await input.fill('Fictional clinician-entered value');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Approve & sign prescription'}).click();
 await expect(page.locator('.timeline article').first()).toContainText('Signed');
 await page.locator('nav').getByRole('button',{name:'Follow-up'}).click();
 await page.getByLabel('Assessment & uncertainty').fill('Cause of change is uncertain. Fictional follow-up.');
 await page.getByRole('button',{name:'Save draft / record'}).click();
 await expect(page.locator('.timeline article').first()).toContainText('Follow-up');
 await page.locator('.timeline article').first().getByText('View record').click();
 await expect(page.locator('.timeline')).toContainText('Cause of change is uncertain');
});
